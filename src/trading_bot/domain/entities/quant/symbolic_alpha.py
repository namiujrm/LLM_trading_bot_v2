"""Symbolic Alpha and Tournament Domain Entities (Clean Architecture, Invariant #9).

Zero Defaults, Zero Class Field Defaults, Zero Silent Fallbacks.
"""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel

CLUSTER_0_REGIME: str = "CLUSTER_0_REGIME"
CLUSTER_1_MICRO: str = "CLUSTER_1_MICRO"
CLUSTER_2_DERIV: str = "CLUSTER_2_DERIV"
CLUSTER_3_CROSS: str = "CLUSTER_3_CROSS"
ALL_CAUSAL_CLUSTERS: tuple[str, ...] = (
    CLUSTER_0_REGIME,
    CLUSTER_1_MICRO,
    CLUSTER_2_DERIV,
    CLUSTER_3_CROSS,
)


class TournamentVerdict(StrEnum):
    """Verdict outcome for the Champion vs. Challenger model tournament."""

    PROMOTE_CHALLENGER_IMMEDIATELY = "PROMOTE_CHALLENGER_IMMEDIATELY"
    RUN_48H_SHADOW_BATTLE = "RUN_48H_SHADOW_BATTLE"
    KEEP_CHAMPION = "KEEP_CHAMPION"


class SymbolicAlphaCandidate(BaseModel):
    """Candidate symbolic alpha expression generated by the Math Alpha Agent."""

    alpha_id: str
    dsl_expression: str
    causal_cluster: str
    long_monotonic_prior: int
    short_monotonic_prior: int
    targeted_blindspot: str
    economic_rationale: str


class AlphaGatekeeperConfig(BaseModel):
    """Strict quantitative configuration parameters for statistical alpha screening."""

    min_valid_sample_ratio: float
    min_series_std: float
    invariance_tol: float
    min_abs_rank_ic: float
    min_abs_icir: float
    min_t_statistic: float
    min_daily_blocks_for_icir: int
    daily_block_bars: int
    min_quantile_monotonicity: float
    max_collinearity_corr: float


class AlphaGateResult(BaseModel):
    """Comprehensive statistical screening verdict for an alpha candidate."""

    alpha_id: str
    passed_all_gates: bool
    failed_stage: str | None
    oos_rank_ic: float
    oos_icir: float
    t_statistic: float
    is_regime_invariant: bool
    quantile_monotonicity_corr: float
    max_corr_with_existing: float


class ModelTournamentReport(BaseModel):
    """Champion vs. Challenger backtest and ML calibration comparison report."""

    created_at_utc: str
    champion_model_id: str
    challenger_model_id: str
    champion_feature_count: int
    challenger_feature_count: int
    # Financial Backtest Metrics
    champion_net_sharpe: float
    challenger_net_sharpe: float
    champion_max_drawdown_pct: float
    challenger_max_drawdown_pct: float
    champion_calmar_ratio: float
    challenger_calmar_ratio: float
    champion_win_rate: float
    challenger_win_rate: float
    champion_profit_factor: float
    challenger_profit_factor: float
    champion_expectancy_r: float
    challenger_expectancy_r: float
    # ML Calibration Metrics
    champion_brier_score: float
    challenger_brier_score: float
    champion_brier_skill_score: float
    challenger_brier_skill_score: float
    champion_log_loss: float
    challenger_log_loss: float
    champion_venn_abers_spread: float
    challenger_venn_abers_spread: float
    # Verdict & Approval
    is_promotable: bool
    recommended_verdict: TournamentVerdict
    approval_checklist: dict[str, bool]
    verdict_rationale: str
